\set ON_ERROR_STOP on

-- ---------------------------------------------------------------- shared
CREATE TABLE IF NOT EXISTS shared.dim_term (
    term_key        integer PRIMARY KEY,          -- 20251 for term 2025-1; -1 = no term
    term_code       text NOT NULL UNIQUE,         -- class standard: 2025-1, 2025-2, 2025-3
    academic_year   text NOT NULL,                -- 2025-2026
    term_name       text NOT NULL,
    start_date      date,
    end_date        date
);

CREATE TABLE IF NOT EXISTS shared.dim_date (
    date_key        integer PRIMARY KEY,          -- yyyymmdd, for example 20260317
    full_date       date NOT NULL UNIQUE,
    day_name        text NOT NULL,
    day_of_week     smallint NOT NULL,            -- 1 = Monday ... 7 = Sunday
    week_of_year    smallint NOT NULL,
    month_no        smallint NOT NULL,
    month_name      text NOT NULL,
    year_month      text NOT NULL,                -- 2026-03
    quarter_no      smallint NOT NULL,
    year_no         smallint NOT NULL,
    is_weekend      boolean NOT NULL,
    is_exam_week    boolean NOT NULL DEFAULT false,
    term_key        integer NOT NULL DEFAULT -1 REFERENCES shared.dim_term (term_key)
);

CREATE TABLE IF NOT EXISTS shared.dim_college (
    college_key     serial PRIMARY KEY,
    college_code    text NOT NULL UNIQUE,         -- CCS, CoE, CBA, CAL, CoS
    college_name    text NOT NULL
);

CREATE TABLE IF NOT EXISTS shared.dim_program (
    program_key     serial PRIMARY KEY,
    program_code    text NOT NULL UNIQUE,
    college_key     integer NOT NULL REFERENCES shared.dim_college (college_key)
);

CREATE TABLE IF NOT EXISTS shared.dim_student (
    student_key     serial PRIMARY KEY,
    student_id      text NOT NULL,                -- cleaned: trimmed, upper case, S + 7 digits
    full_name       text,
    program_key     integer REFERENCES shared.dim_program (program_key),
    year_level      smallint,
    valid_from      date NOT NULL DEFAULT DATE '1900-01-01',
    valid_to        date NOT NULL DEFAULT DATE '9999-12-31',
    is_current      boolean NOT NULL DEFAULT true,
    UNIQUE (student_id, valid_from)
);

-- ------------------------------------------------------------------ mart
CREATE TABLE IF NOT EXISTS mart.dim_branch (
    branch_key      serial PRIMARY KEY,
    branch_code     text NOT NULL UNIQUE,
    branch_name     text NOT NULL,
    branch_type     text NOT NULL CHECK (branch_type IN ('BOOKSTORE', 'CANTEEN')),
    building        text
);

-- Type 2 on unit_price: one row per product per price period.
CREATE TABLE IF NOT EXISTS mart.dim_product (
    product_key     serial PRIMARY KEY,
    product_code    text NOT NULL,
    product_name    text NOT NULL,
    category        text NOT NULL,
    unit_price      numeric(10,2) NOT NULL,
    valid_from      timestamp NOT NULL DEFAULT TIMESTAMP '1900-01-01',
    valid_to        timestamp NOT NULL DEFAULT TIMESTAMP '9999-12-31',
    is_current      boolean NOT NULL DEFAULT true,
    UNIQUE (product_code, valid_from)
);

-- customer_key -1 = unknown buyer (walk-in, or an id the store does not know).
CREATE TABLE IF NOT EXISTS mart.dim_customer (
    customer_key    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id     text NOT NULL UNIQUE,
    customer_type   text NOT NULL CHECK (customer_type IN ('STUDENT', 'STAFF', 'UNKNOWN')),
    student_id      text,                         -- joins to shared.dim_student.student_id
    staff_no        text
);

-- Grain: one row per item sold per receipt (one receipt line).
CREATE TABLE IF NOT EXISTS mart.fct_sales (
    sales_key           bigserial PRIMARY KEY,
    receipt_no          text NOT NULL,            -- degenerate dimension
    line_no             integer NOT NULL,         -- degenerate dimension
    date_key            integer NOT NULL REFERENCES shared.dim_date (date_key),
    term_key            integer NOT NULL REFERENCES shared.dim_term (term_key),
    branch_key          integer NOT NULL REFERENCES mart.dim_branch (branch_key),
    product_key         integer NOT NULL REFERENCES mart.dim_product (product_key),
    customer_key        integer NOT NULL REFERENCES mart.dim_customer (customer_key),
    txn_type            text NOT NULL CHECK (txn_type IN ('SALE', 'REFUND')),
    payment_method      text,
    quantity            integer NOT NULL CHECK (quantity > 0),
    unit_price          numeric(10,2) NOT NULL,
    discount_amount     numeric(10,2) NOT NULL DEFAULT 0,
    line_amount         numeric(12,2) NOT NULL,   -- quantity * unit_price - discount_amount
    sold_at             timestamp NOT NULL,
    source_updated_at   timestamp NOT NULL,
    loaded_at           timestamptz NOT NULL DEFAULT now(),
    UNIQUE (receipt_no, line_no)
);
